use std::{collections::HashSet, fmt::Write as _};

pub const HYPRLAND_RULESET: &str = "0.57.2";

#[derive(Debug, PartialEq, Eq)]
pub struct Warning {
    pub line: usize,
    pub message: String,
}

#[derive(Debug, PartialEq, Eq)]
pub struct Conversion {
    pub lua: String,
    pub warnings: Vec<Warning>,
}

#[derive(Debug)]
enum Item {
    Comment(String),
    Assignment {
        key: String,
        value: String,
        line: usize,
    },
    Section {
        name: String,
        items: Vec<Item>,
        line: usize,
    },
}

pub fn convert(input: &str) -> Result<Conversion, String> {
    let mut stack = vec![("root".to_string(), Vec::new(), 0)];

    for (index, raw) in input.lines().enumerate() {
        let line = index + 1;
        let trimmed = raw.trim();
        if trimmed.is_empty() {
            continue;
        }
        if let Some(comment) = trimmed.strip_prefix('#') {
            stack
                .last_mut()
                .expect("root exists")
                .1
                .push(Item::Comment(comment.trim().into()));
            continue;
        }

        let code = strip_comment(trimmed).trim();
        if code.is_empty() {
            continue;
        }
        if code == "}" {
            if stack.len() == 1 {
                return Err(format!("line {line}: unmatched closing brace"));
            }
            let (name, items, start) = stack.pop().expect("checked length");
            stack
                .last_mut()
                .expect("parent exists")
                .1
                .push(Item::Section {
                    name,
                    items,
                    line: start,
                });
            continue;
        }
        if let Some((name, body)) = inline_section(code) {
            let item = parse_assignment(body, line)?;
            stack
                .last_mut()
                .expect("root exists")
                .1
                .push(Item::Section {
                    name: name.into(),
                    items: vec![item],
                    line,
                });
            continue;
        }
        if let Some(name) = code.strip_suffix('{') {
            stack.push((name.trim().into(), Vec::new(), line));
            continue;
        }
        stack
            .last_mut()
            .expect("root exists")
            .1
            .push(parse_assignment(code, line)?);
    }

    if stack.len() != 1 {
        let (name, _, line) = stack.last().expect("non-empty");
        return Err(format!("line {line}: section {name:?} is not closed"));
    }

    let (_, items, _) = stack.pop().expect("root exists");
    Ok(Emitter::default().emit(&items))
}

fn parse_assignment(code: &str, line: usize) -> Result<Item, String> {
    let Some((key, value)) = code.split_once('=') else {
        return Err(format!("line {line}: expected an assignment or section"));
    };
    Ok(Item::Assignment {
        key: key.trim().into(),
        value: value.trim().into(),
        line,
    })
}

fn inline_section(code: &str) -> Option<(&str, &str)> {
    let (name, rest) = code.split_once('{')?;
    Some((name.trim(), rest.strip_suffix('}')?.trim()))
}

fn strip_comment(line: &str) -> &str {
    let mut single = false;
    let mut double = false;
    let mut escaped = false;
    for (index, ch) in line.char_indices() {
        if escaped {
            escaped = false;
            continue;
        }
        match ch {
            '\\' if single || double => escaped = true,
            '\'' if !double => single = !single,
            '"' if !single => double = !double,
            '#' if !single && !double => return &line[..index],
            _ => {}
        }
    }
    line
}

#[derive(Default)]
struct Emitter {
    output: String,
    warnings: Vec<Warning>,
    variables: HashSet<String>,
}

impl Emitter {
    fn emit(mut self, items: &[Item]) -> Conversion {
        self.variables
            .extend(items.iter().filter_map(|item| match item {
                Item::Assignment { key, .. } => key.strip_prefix('$').map(lua_ident),
                _ => None,
            }));
        writeln!(
            self.output,
            "-- Generated by lang2lua for Hyprland {HYPRLAND_RULESET}.\n"
        )
        .unwrap();
        if !self.variables.is_empty() {
            writeln!(self.output, "_hyprlang_vars = _hyprlang_vars or {{}}").unwrap();
        }

        let execs: Vec<_> = items
            .iter()
            .filter_map(|item| match item {
                Item::Assignment { key, value, .. } if key == "exec-once" => Some(value.as_str()),
                _ => None,
            })
            .collect();

        for item in items {
            match item {
                Item::Comment(text) => {
                    writeln!(self.output, "-- {text}").unwrap();
                }
                Item::Section { name, items, line } => self.section(name, items, *line),
                Item::Assignment { key, value, line } if key == "exec-once" => {}
                Item::Assignment { key, value, line } => self.directive(key, value, *line),
            }
        }

        if !execs.is_empty() {
            writeln!(self.output, "\nhl.on(\"hyprland.start\", function()").unwrap();
            for command in execs {
                writeln!(
                    self.output,
                    "    hl.exec_cmd({})",
                    string_expr(command, &self.variables, false)
                )
                .unwrap();
            }
            writeln!(self.output, "end)").unwrap();
        }

        Conversion {
            lua: self.output,
            warnings: self.warnings,
        }
    }

    fn directive(&mut self, key: &str, value: &str, line: usize) {
        if let Some(variable) = key.strip_prefix('$') {
            writeln!(
                self.output,
                "_hyprlang_vars.{} = {}",
                lua_ident(variable),
                string_expr(value, &self.variables, false)
            )
            .unwrap();
            return;
        }
        match key {
            "autogenerated" => writeln!(
                self.output,
                "hl.config({{ autogenerated = {} }})",
                lua_value(value)
            )
            .unwrap(),
            "source" => writeln!(self.output, "require({})", quote(&module_name(value))).unwrap(),
            "monitor" => self.monitor(value, line),
            "layerrule" => self.rule("layer", value, line),
            "windowrule" | "windowrulev2" => self.rule("window", value, line),
            "env" | "envd" => self.env(value, key == "envd", line),
            key if key.starts_with("bind") => self.bind(key, value, line),
            _ => self.unsupported(
                line,
                format!("unsupported directive {key:?}"),
                Some(format!("{key} = {value}")),
            ),
        }
    }

    fn section(&mut self, name: &str, items: &[Item], line: usize) {
        if name == "animations" {
            let regular: Vec<_> = items.iter().filter(|item| !matches!(item, Item::Assignment { key, .. } if key == "bezier" || key == "animation")).collect();
            if !regular.is_empty() {
                self.config_section(name, &regular);
            }
            for item in items {
                if let Item::Assignment { key, value, line } = item {
                    if key == "bezier" {
                        self.curve(value, *line);
                    }
                    if key == "animation" {
                        self.animation(value, *line);
                    }
                }
            }
        } else if name == "gestures" {
            for item in items {
                if let Item::Assignment { key, value, line } = item {
                    if key == "gesture" {
                        self.gesture(value, *line);
                    } else {
                        self.unsupported(
                            *line,
                            format!("unsupported gestures entry {key:?}"),
                            None,
                        );
                    }
                }
            }
        } else {
            if name == "plugin" {
                self.warnings.push(Warning { line, message: "plugin settings require the matching plugin to be loaded before this module".into() });
            }
            let refs: Vec<_> = items.iter().collect();
            self.config_section(name, &refs);
        }
    }

    fn config_section(&mut self, name: &str, items: &[&Item]) {
        writeln!(self.output, "\nhl.config({{").unwrap();
        writeln!(self.output, "    {} = {{", table_key(name)).unwrap();
        self.table(items, 2);
        writeln!(self.output, "    }},\n}})").unwrap();
    }

    fn table(&mut self, items: &[&Item], depth: usize) {
        let indent = "    ".repeat(depth);
        let mut emitted_paths = HashSet::new();
        for item in items {
            match item {
                Item::Comment(text) => {
                    writeln!(self.output, "{indent}-- {text}").unwrap();
                }
                Item::Assignment { key, value, line } => {
                    if key.contains('-') {
                        self.unsupported(
                            *line,
                            format!("plugin/list entry {key:?} needs manual conversion"),
                            None,
                        );
                        writeln!(self.output, "{indent}-- TODO: {} = {}", key, value).unwrap();
                    } else if let Some((prefix, _)) = key.split_once('.') {
                        if emitted_paths.insert(prefix) {
                            writeln!(self.output, "{indent}{} = {{", table_key(prefix)).unwrap();
                            let mut paths = Vec::new();
                            for nested in items {
                                if let Item::Assignment { key, value, .. } = nested
                                    && let Some(suffix) = key.strip_prefix(&format!("{prefix}."))
                                {
                                    paths.push((suffix.split('.').collect(), value.as_str()));
                                }
                            }
                            self.table_paths(&paths, depth + 1);
                            writeln!(self.output, "{indent}}},").unwrap();
                        }
                    } else {
                        self.table_path(&[key], value, depth);
                    }
                }
                Item::Section { name, items, .. } => {
                    writeln!(self.output, "{indent}{} = {{", table_key(name)).unwrap();
                    let refs: Vec<_> = items.iter().collect();
                    self.table(&refs, depth + 1);
                    writeln!(self.output, "{indent}}},").unwrap();
                }
            }
        }
    }

    fn table_path(&mut self, path: &[&str], value: &str, depth: usize) {
        let indent = "    ".repeat(depth);
        if path.len() == 1 {
            writeln!(
                self.output,
                "{indent}{} = {},",
                table_key(path[0]),
                lua_value(value)
            )
            .unwrap();
        } else {
            writeln!(self.output, "{indent}{} = {{", table_key(path[0])).unwrap();
            self.table_path(&path[1..], value, depth + 1);
            writeln!(self.output, "{indent}}},").unwrap();
        }
    }

    fn table_paths(&mut self, paths: &[(Vec<&str>, &str)], depth: usize) {
        let indent = "    ".repeat(depth);
        let mut emitted = HashSet::new();
        for (path, value) in paths {
            let Some(first) = path.first() else { continue };
            if !emitted.insert(*first) {
                continue;
            }
            let nested: Vec<_> = paths
                .iter()
                .filter(|(candidate, _)| candidate.first() == Some(first) && candidate.len() > 1)
                .map(|(candidate, value)| (candidate[1..].to_vec(), *value))
                .collect();
            if nested.is_empty() {
                writeln!(
                    self.output,
                    "{indent}{} = {},",
                    table_key(first),
                    lua_value(value)
                )
                .unwrap();
            } else {
                writeln!(self.output, "{indent}{} = {{", table_key(first)).unwrap();
                self.table_paths(&nested, depth + 1);
                writeln!(self.output, "{indent}}},").unwrap();
            }
        }
    }

    fn monitor(&mut self, value: &str, line: usize) {
        let fields = split_csv(value);
        if fields.len() < 4 {
            self.unsupported(
                line,
                "monitor needs at least output, mode, position, and scale".into(),
                None,
            );
            return;
        }
        write!(
            self.output,
            "hl.monitor({{ output = {}, mode = {}, position = {}, scale = {}",
            quote(fields[0]),
            quote(fields[1]),
            quote(fields[2]),
            lua_value(fields[3])
        )
        .unwrap();
        let mut extra = fields[4..].chunks_exact(2);
        for pair in &mut extra {
            write!(
                self.output,
                ", {} = {}",
                table_key(pair[0]),
                lua_value(pair[1])
            )
            .unwrap();
        }
        if !extra.remainder().is_empty() {
            self.warnings.push(Warning {
                line,
                message: "monitor has an unmatched extra field".into(),
            });
        }
        writeln!(self.output, " }})").unwrap();
    }

    fn env(&mut self, value: &str, force: bool, line: usize) {
        let fields = split_csv(value);
        if fields.len() < 2 {
            self.unsupported(
                line,
                "environment directive needs a name and value".into(),
                None,
            );
            return;
        }
        let joined = fields[1..].join(",");
        if force {
            writeln!(
                self.output,
                "hl.env({}, {}, {{ force = true }})",
                quote(fields[0]),
                string_expr(&joined, &self.variables, false)
            )
            .unwrap();
        } else {
            writeln!(
                self.output,
                "hl.env({}, {})",
                quote(fields[0]),
                string_expr(&joined, &self.variables, false)
            )
            .unwrap();
        }
    }

    fn curve(&mut self, value: &str, line: usize) {
        let f = split_csv(value);
        if f.len() != 5 {
            self.unsupported(line, "bezier needs a name and four points".into(), None);
            return;
        }
        writeln!(
            self.output,
            "hl.curve({}, {{ type = \"bezier\", points = {{ {{{}, {}}}, {{{}, {}}} }} }})",
            quote(f[0]),
            f[1],
            f[2],
            f[3],
            f[4]
        )
        .unwrap();
    }

    fn animation(&mut self, value: &str, line: usize) {
        let f = split_csv(value);
        if f.len() < 4 {
            self.unsupported(
                line,
                "animation needs leaf, enabled, speed, and curve".into(),
                None,
            );
            return;
        }
        write!(
            self.output,
            "hl.animation({{ leaf = {}, enabled = {}, speed = {}, bezier = {}",
            quote(f[0]),
            boolish(f[1]),
            f[2],
            quote(f[3])
        )
        .unwrap();
        if f.len() > 4 {
            write!(self.output, ", style = {}", quote(&f[4..].join(", "))).unwrap();
        }
        writeln!(self.output, " }})").unwrap();
    }

    fn gesture(&mut self, value: &str, line: usize) {
        let f = split_csv(value);
        if f.len() < 3 {
            self.unsupported(
                line,
                "gesture needs fingers, direction, and action".into(),
                None,
            );
            return;
        }
        writeln!(
            self.output,
            "hl.gesture({{ fingers = {}, direction = {}, action = {} }})",
            f[0],
            quote(f[1]),
            quote(&f[2..].join(", "))
        )
        .unwrap();
    }

    fn rule(&mut self, kind: &str, value: &str, line: usize) {
        let fields = split_csv(value);
        let mut effects = Vec::new();
        let mut matches = Vec::new();
        for field in fields {
            if let Some(rest) = field.strip_prefix("match:") {
                if let Some((key, value)) = rest.split_once(' ') {
                    matches.push((key, value));
                } else {
                    self.unsupported(line, format!("invalid rule matcher {field:?}"), None);
                }
            } else if let Some((key, value)) = field.split_once(' ') {
                effects.push((key, value));
            } else {
                effects.push((field, "true"));
            }
        }
        if matches.is_empty() {
            self.unsupported(
                line,
                format!("legacy {kind} rule has no match: selector"),
                Some(value.into()),
            );
            return;
        }
        writeln!(self.output, "hl.{kind}_rule({{").unwrap();
        write!(self.output, "    match = {{ ").unwrap();
        for (key, value) in matches {
            write!(self.output, "{} = {}, ", table_key(key), lua_value(value)).unwrap();
        }
        writeln!(self.output, "}},").unwrap();
        for (key, value) in effects {
            writeln!(
                self.output,
                "    {} = {},",
                table_key(key),
                lua_value(value)
            )
            .unwrap();
        }
        writeln!(self.output, "}})").unwrap();
    }

    fn bind(&mut self, family: &str, value: &str, line: usize) {
        let flags = family.strip_prefix("bind").unwrap_or_default();
        let offset = usize::from(flags.contains('d'));
        let f: Vec<_> = value.splitn(4 + offset, ',').map(str::trim).collect();
        let description = flags.contains('d').then(|| f.get(2).copied()).flatten();
        if f.len() < 3 + offset {
            self.unsupported(line, format!("{family} has too few fields"), None);
            return;
        }
        let keys = bind_keys(f[0], f[1]);
        let dispatcher = f[2 + offset].trim().to_ascii_lowercase();
        let args = f
            .get(3 + offset..)
            .unwrap_or_default()
            .join(",")
            .trim()
            .to_string();
        let action = if flags.contains('m') && dispatcher == "movewindow" {
            Some("hl.dsp.window.drag()".into())
        } else {
            dispatcher_expr(&dispatcher, &args, &self.variables)
        };
        let Some(action) = action else {
            self.unsupported(
                line,
                format!("unsupported dispatcher {dispatcher:?}"),
                Some(value.into()),
            );
            return;
        };
        let mut options = Vec::new();
        for flag in flags.chars() {
            let option = match flag {
                'e' => "repeating = true",
                'l' => "locked = true",
                'r' => "release = true",
                'n' => "non_consuming = true",
                't' => "transparent = true",
                'i' => "ignore_mods = true",
                'o' => "dont_inhibit = true",
                'p' => "long_press = true",
                'u' => "submap_universal = true",
                'c' => "click = true",
                'm' => "drag = true",
                'd' => continue,
                _ => {
                    self.warnings.push(Warning {
                        line,
                        message: format!("unknown bind flag {flag:?}"),
                    });
                    continue;
                }
            };
            options.push(option.to_string());
        }
        if let Some(description) = description {
            options.push(format!("description = {}", quote(description)));
        }
        if options.is_empty() {
            writeln!(
                self.output,
                "hl.bind({}, {action})",
                string_expr(&keys, &self.variables, true)
            )
            .unwrap();
        } else {
            writeln!(
                self.output,
                "hl.bind({}, {action}, {{ {} }})",
                string_expr(&keys, &self.variables, true),
                options.join(", ")
            )
            .unwrap();
        }
    }

    fn unsupported(&mut self, line: usize, message: String, legacy: Option<String>) {
        self.warnings.push(Warning { line, message });
        if let Some(legacy) = legacy {
            writeln!(
                self.output,
                "-- TODO(lang2lua): {}",
                legacy.replace('\n', " ")
            )
            .unwrap();
        }
    }
}

fn dispatcher_expr(name: &str, args: &str, variables: &HashSet<String>) -> Option<String> {
    let q = || quote(args);
    Some(match name {
        "exec" => format!("hl.dsp.exec_cmd({})", string_expr(args, variables, false)),
        "killactive" => "hl.dsp.window.close()".into(),
        "togglefloating" => "hl.dsp.window.float({})".into(),
        "pin" => "hl.dsp.window.pin({})".into(),
        "pseudo" => "hl.dsp.window.pseudo({})".into(),
        "movewindow" => format!("hl.dsp.window.move({{ direction = {} }})", q()),
        "resizeactive" => format!("hl.dsp.window.resize({{ delta = {} }})", q()),
        "movefocus" => format!("hl.dsp.focus({{ direction = {} }})", q()),
        "workspace" => format!("hl.dsp.focus({{ workspace = {} }})", q()),
        "movetoworkspace" => format!(
            "hl.dsp.window.move({{ workspace = {}, follow = true }})",
            q()
        ),
        "movetoworkspacesilent" => format!(
            "hl.dsp.window.move({{ workspace = {}, follow = false }})",
            q()
        ),
        "movecurrentworkspacetomonitor" => {
            format!("hl.dsp.workspace.move({{ monitor = {} }})", q())
        }
        "togglespecialworkspace" => format!(
            "hl.dsp.workspace.toggle_special({})",
            quote(args.strip_prefix("special:").unwrap_or(args))
        ),
        "fullscreen" => format!(
            "hl.dsp.window.fullscreen({{ mode = {} }})",
            quote(if args == "1" {
                "maximized"
            } else {
                "fullscreen"
            })
        ),
        "cyclenext" => "hl.dsp.window.cycle_next({})".into(),
        "bringactivetotop" => "hl.dsp.window.alter_zorder({ mode = \"top\" })".into(),
        "togglesplit" => "hl.dsp.layout(\"togglesplit\")".into(),
        "submap" => format!("hl.dsp.submap({})", q()),
        "sendshortcut" => {
            let f = split_csv(args);
            if f.len() < 2 {
                return None;
            }
            format!(
                "hl.dsp.send_shortcut({{ mods = {}, key = {} }})",
                quote(f[0]),
                quote(f[1])
            )
        }
        "dragwindow" | "movewindowmouse" => "hl.dsp.window.drag()".into(),
        "resizewindow" => "hl.dsp.window.resize()".into(),
        _ => return None,
    })
}

fn split_csv(value: &str) -> Vec<&str> {
    value.split(',').map(str::trim).collect()
}

fn bind_keys(mods: &str, key: &str) -> String {
    mods.split(['+', ' '])
        .filter(|part| !part.is_empty())
        .chain([key.trim()])
        .collect::<Vec<_>>()
        .join(" + ")
}

fn boolish(value: &str) -> &str {
    match value.trim() {
        "0" => "false",
        "1" => "true",
        other => other,
    }
}

fn lua_value(value: &str) -> String {
    let value = value.trim();
    if matches!(value, "true" | "false") || value.parse::<f64>().is_ok() || value.starts_with("0x")
    {
        value.into()
    } else {
        quote(value)
    }
}

fn string_expr(value: &str, variables: &HashSet<String>, all_variables: bool) -> String {
    let value = value.trim();
    let mut pieces = Vec::new();
    let mut literal_start = 0;
    let mut search_start = 0;
    while let Some(relative_index) = value[search_start..].find('$') {
        let index = search_start + relative_index;
        let tail = &value[index + 1..];
        let length = tail
            .chars()
            .take_while(|ch| ch.is_ascii_alphanumeric() || *ch == '_')
            .count();
        if length == 0 {
            search_start = index + 1;
            continue;
        }
        let variable = lua_ident(&tail[..length]);
        if all_variables || variables.contains(&variable) {
            if index > literal_start {
                pieces.push(quote(&value[literal_start..index]));
            }
            pieces.push(format!("_hyprlang_vars.{variable}"));
            literal_start = index + length + 1;
            search_start = literal_start;
        } else {
            search_start = index + length + 1;
        }
    }
    if literal_start < value.len() || pieces.is_empty() {
        pieces.push(quote(&value[literal_start..]));
    }
    pieces.join(" .. ")
}

fn quote(value: &str) -> String {
    format!(
        "\"{}\"",
        value
            .replace('\\', "\\\\")
            .replace('"', "\\\"")
            .replace('\n', "\\n")
    )
}

fn lua_ident(value: &str) -> String {
    let mut result = String::new();
    for (index, ch) in value.chars().enumerate() {
        if (index == 0 && (ch.is_ascii_alphabetic() || ch == '_'))
            || (index > 0 && (ch.is_ascii_alphanumeric() || ch == '_'))
        {
            result.push(ch);
        } else {
            result.push('_');
        }
    }
    result
}

fn table_key(value: &str) -> String {
    let ident = lua_ident(value);
    if ident == value {
        ident
    } else {
        format!("[{}]", quote(value))
    }
}

fn module_name(value: &str) -> String {
    value
        .trim()
        .trim_start_matches("~/.config/hypr/")
        .trim_end_matches(".conf")
        .trim_end_matches(".lua")
        .replace('/', ".")
}

