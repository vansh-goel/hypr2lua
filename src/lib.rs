    fn converts_nested_config_and_special_directives() {
        let input = r#"
$mainMod = SUPER
monitor = , preferred, auto, 1
general {
  gaps_in = 4
  col.active_border = rgba(1122E1D1)
  col.inactive_border = rgba(31313600)
}
group {
  groupbar.col.active = rgba(ffffffff)
  groupbar.col.inactive = rgba(000000ff)
}
animations {
  enabled = true
  bezier = soft, 0.2, 0, 0, 1
  animation = windows, 1, 3, soft, popin 60%
}
bindle = $mainMod, XF86AudioRaiseVolume, exec, wpctl set-volume 5%+
bind = SUPER, P, pin
bindm = $mainMod, mouse:272, movewindow
bind = SUPER, S, exec, grim -g "$(slurp $SLURP_ARGS)"
"#;
        let result = convert(input).expect("valid fixture");
        assert!(result.warnings.is_empty(), "{:?}", result.warnings);
        assert!(
            result
                .lua
                .contains("col = {\n            active_border = \"rgba(1122E1D1)\"")
        );
        assert_eq!(
            result
                .lua
                .lines()
                .filter(|line| *line == "        col = {")
                .count(),
            1
        );
        assert!(result.lua.contains("inactive_border = \"rgba(31313600)\""));
        assert_eq!(
            result
                .lua
                .lines()
                .filter(|line| *line == "        groupbar = {")
                .count(),
            1
        );
        assert_eq!(
            result
                .lua
                .lines()
                .filter(|line| *line == "            col = {")
                .count(),
            1
        );
        assert!(result.lua.contains("hl.curve(\"soft\""));
        assert!(result.lua.contains("{ locked = true, repeating = true }"));
        assert!(
            result
                .lua
                .contains("_hyprlang_vars.mainMod .. \" + XF86AudioRaiseVolume\"")
        );
        assert!(result.lua.contains("hl.dsp.window.pin({})"));
        assert!(result.lua.contains("hl.dsp.window.drag()"));
        assert!(result.lua.contains("$(slurp "));
        assert!(result.lua.contains("$SLURP_ARGS"));
    }

    #[test]
    fn warns_without_leaking_unsupported_input_into_executable_lua() {
        let result = convert("mystery = private-value\n").expect("valid assignment");
        assert_eq!(result.warnings.len(), 1);
        assert!(
            result
                .lua
                .contains("-- TODO(lang2lua): mystery = private-value")
        );
    }

    #[test]
    fn rejects_unclosed_sections() {
        assert!(convert("general {\n gaps_in = 2\n").is_err());
    }
